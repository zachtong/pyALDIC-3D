def fill_locale(locale: str) -> tuple[int, list[str]]:
    """Fill one ``.ts`` in place; return (filled_count, missing_sources)."""
    table = TRANSLATIONS[locale]
    path = SRC_DIR / f"al_dic_3d_{locale}.ts"
    text = path.read_text(encoding="utf-8")
    missing: list[str] = []
    count = 0

    def _sub(m: re.Match) -> str:
        nonlocal count
        source = unescape(m.group("src"))
        translation = table.get(source)
        if translation is None:
            missing.append(source)
            return m.group(0)
        count += 1
        return f"{m.group(1)}>{escape(translation)}</translation>"

    path.write_text(_MSG_RE.sub(_sub, text), encoding="utf-8")
    return count, missing


